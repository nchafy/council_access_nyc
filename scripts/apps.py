#!/usr/bin/env python3
"""Regenerate the app manifest, or check it against the folders on disk.

    python3 scripts/apps.py           regenerate src/showup/apps/manifest.mjs
    python3 scripts/apps.py --check   exit 1 if it disagrees with the folders

A browser cannot list a directory over static HTTP: there is no request that answers "what is
in /apps". So something has to write the answer down, and this writes it. `--check` exists
because a stale manifest is the one failure of this arrangement that looks like nothing at
all — the app is simply not on the desktop, and nothing errors.

The contract is webxp's, in that project's `docs/apps.md`: a folder under `apps/` whose
`app.mjs` default-exports a spec whose `id` equals the folder name. Nothing here imports or
parses JavaScript — the folder names are the whole input, and webxp's loader validates the
specs at runtime where it can actually read them.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
APPS_DIR = REPO_ROOT / "src" / "showup" / "apps"
MANIFEST = APPS_DIR / "manifest.mjs"

#: An app id is a folder name, and it also becomes a CSS class (`app-<id>`) and part of a URL.
#: Lower-case, digits and dashes keep it valid in all three without escaping.
ID_PATTERN = re.compile(r"^[a-z][a-z0-9-]*$")

HEADER = """/* The app directory.
 *
 * Generated by `scripts/apps.py`. Do not edit by hand: the next run overwrites it.
 *
 * A browser cannot list a directory over static HTTP, so this file is how the desktop knows
 * which folders under `apps/` exist. Order is the Start menu's order, which is why it is
 * sorted rather than left to the filesystem.
 */
"""


def app_ids() -> list[str]:
    """Every folder under `apps/` that carries an `app.mjs`, sorted.

    A folder without `app.mjs` is not an app — it is a mistake or a leftover, and listing it
    would make the desktop report a broken program for something that was never one.
    """
    found = []
    for path in sorted(APPS_DIR.iterdir()):
        if not path.is_dir():
            continue
        if not (path / "app.mjs").is_file():
            continue
        if not ID_PATTERN.match(path.name):
            raise SystemExit(
                f"apps/{path.name}: an app id must match {ID_PATTERN.pattern} — it becomes a "
                "CSS class and part of a URL"
            )
        found.append(path.name)
    return found


def render(ids: list[str]) -> str:
    lines = "\n".join(f"  '{app_id}'," for app_id in ids)
    return f"{HEADER}export const APPS = [\n{lines}\n];\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 on disagreement")
    args = parser.parse_args(argv)

    wanted = render(app_ids())
    if args.check:
        found = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
        if found != wanted:
            print(
                f"{MANIFEST.relative_to(REPO_ROOT)} is stale. Run `python3 scripts/apps.py`.",
                file=sys.stderr,
            )
            print(f"  on disk: {app_ids()}", file=sys.stderr)
            return 1
        print(f"manifest is current: {len(app_ids())} apps")
        return 0

    MANIFEST.write_text(wanted, encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(REPO_ROOT)}: {', '.join(app_ids())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
